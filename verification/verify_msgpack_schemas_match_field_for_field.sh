N_PAIRS="$(python3 -c 'import json;print(len(json.load(open("'"$WORK"'/input.json"))["pairs"]))')"
assert_ge "the comparison covers a meaningful number of declared pairs" 15 "$N_PAIRS"

# ---------------------------------------------------------------------------
# §4  The comparison, and its result — whatever it is
# ---------------------------------------------------------------------------
m37_bounded_out "$WORK/out.json" "$WORK/out.err" "$M37_BOUND" python3 "$CMP" --input "$WORK/input.json"
CMP_RC=$?
assert_true "the comparison produced a machine-readable report" test -s "$WORK/out.json"
assert_true "…and the comparer did not fail on a malformed input (that is exit 2)" test "$CMP_RC" -ne 2

read -r N_AGREE N_DIFFER N_UNREAD VERDICT <<EOF
$(python3 -c '
import json,sys
d=json.load(open(sys.argv[1]))
print(len(d["agree"]),len(d["differ"]),len(d["unreadable"]),d["verdict"])' "$WORK/out.json")
EOF

assert_eq "every declared pair was readable on both sides" "0" "$N_UNREAD"
assert_eq "…and every pair is accounted for in exactly one bucket" \
  "$N_PAIRS" "$((N_AGREE + N_DIFFER + N_UNREAD))"

# EVERY ROW IS PRINTED, agreements included, and each disagreement PRINTS ITS
# RESIDUE — this campaign's rule for scanners is that they print what they could
# not place rather than reporting a count.
python3 - "$WORK/out.json" <<'PY'
import json, sys
d = json.load(open(sys.argv[1]))
for r in d["rows"]:
    print("  --   {:<10} {}".format(r["verdict"], r["id"]))
    if r["verdict"] == "UNREADABLE":
        print("  --              " + str(r.get("reason")))
        continue
    print("  --              schema: " + str(r["schema"]["wire"]))
    print("  --              cpp   : " + str(r["cpp"]["wire"]) + "  via " + str(r["cpp"]["macro"]))
    if r["verdict"] == "DIFFER":
        print("  --              only in the schema: " + str(r["only_in_schema"]))
        print("  --              only in the C++   : " + str(r["only_in_cpp"]))
PY

# THE MEASURED RESULT. These are pinned as what was measured on 2026-08-30 at the
# `cpp` anchor, per pair by NAME rather than as a total, because a total moving
# from 8/5 to 7/6 would otherwise say nothing about WHICH pair moved. M37's own
# section says a disagreement is a result to record; this is the record.
AGREE_SET="$(python3 -c 'import json,sys;print(" ".join(sorted(json.load(open(sys.argv[1]))["agree"])))' "$WORK/out.json")"
DIFFER_SET="$(python3 -c 'import json,sys;print(" ".join(sorted(json.load(open(sys.argv[1]))["differ"])))' "$WORK/out.json")"

assert_eq "the pairs that agree field for field are exactly these" \
  "IndexedNullifierLeafValue IndexedPublicDataLeafValue NullifierLeafUpdateWitnessData NullifierLeafValue PublicDataLeafUpdateWitnessData PublicDataLeafValue SiblingPathAndIndex WorldStateRevision avm.error avm.error-vs-bbapi wsdb.error" \
  "$AGREE_SET"
assert_eq "…and the pairs that do NOT are exactly these" \
  "FindLowLeaf.response GetTreeInfo.response SequentialInsertionResultNullifier SequentialInsertionResultPublicData Simulate.request SimulateWithHints.request TreeStateReference" \
  "$DIFFER_SET"
assert_eq "so the overall verdict is the one M37 must record" "not-field-for-field" "$VERDICT"
assert_eq "the comparer's exit status agrees with its own verdict" "3" "$CMP_RC"

# The two disagreements that are about a SPELLING and not about a shape, pinned by
# the exact residues, because "they differ" is not a finding and "they differ by
# snake_case versus camelCase in the one type upstream forgot to camel-case" is.
row() { python3 -c '
import json,sys
d=json.load(open(sys.argv[1]))
r=[x for x in d["rows"] if x["id"]==sys.argv[2]][0]
print(" ".join(r[sys.argv[3]]))' "$WORK/out.json" "$1" "$2"; }

assert_eq "SequentialInsertionResult: the schema carries the camelCase spelling" \
  "insertionWitnessData lowLeafWitnessData" "$(row SequentialInsertionResultNullifier only_in_schema)"
assert_eq "…while the C++ carries the raw member names, because it uses SERIALIZATION_FIELDS" \
  "insertion_witness_data low_leaf_witness_data" "$(row SequentialInsertionResultNullifier only_in_cpp)"
assert_eq "FindLowLeaf: the schema drops the is_ prefix as well as changing the case" \
  "alreadyPresent" "$(row FindLowLeaf.response only_in_schema)"
assert_eq "…against the C++ member the reactor's export returns" \
  "is_already_present" "$(row FindLowLeaf.response only_in_cpp)"

# And the two that are about a SHAPE. The AVM schema carries the payload as one
# opaque `bytes` field, so it declares NO AVM field at all — which is why the
# "two transports over one schema" sentence is true of the transport and false of
# the declaration.
assert_eq "the bb-avm-sim schema's Simulate request declares exactly one field" \
  "inputs" "$(python3 -c '
import json,sys
d=json.load(open(sys.argv[1]))
r=[x for x in d["rows"] if x["id"]=="Simulate.request"][0]
print(" ".join(r["schema"]["wire"]))' "$WORK/out.json")"
assert_eq "…and it is not any field of the type our export actually takes" \
  "inputs" "$(row Simulate.request only_in_schema)"
assert_ge "…while that type has a real field list on our side" 3 \
  "$(python3 -c '
import json,sys
d=json.load(open(sys.argv[1]))
r=[x for x in d["rows"] if x["id"]=="Simulate.request"][0]
print(len(r["cpp"]["wire"]))' "$WORK/out.json")"

# ---------------------------------------------------------------------------
# §5  THE NEGATIVE CONTROL: a fabricated field must be reported missing, by name
# ---------------------------------------------------------------------------
m37_bounded_out "$WORK/out-injected.json" "$WORK/out-injected.err" "$M37_BOUND" python3 "$CMP" --input "$WORK/input-injected.json"
INJ_RC=$?
# NOT "the comparer still exits 3". THAT ASSERTION COULD NOT FAIL BECAUSE OF THE PLANT:
# the UNPLANTED run already exits 3, since seven pairs differ without any help, so the
# comparison was true whether or not the plant was ever seen. It caught a crash and
# nothing else, while its description claimed to measure the control. What the plant
# must do is MOVE THE COUNTS — one pair leaves `agree` and joins `differ` — and that is
# false of a comparer that stopped comparing, which is the state the control exists for.
assert_eq "the comparer does not fail on the injected input either (that would be exit 2)" "3" "$INJ_RC"
INJ_AGREE="$(python3 -c 'import json,sys;d=json.load(open(sys.argv[1]));print(len(d["agree"]))' "$WORK/out-injected.json")"
INJ_DIFFER="$(python3 -c 'import json,sys;d=json.load(open(sys.argv[1]));print(len(d["differ"]))' "$WORK/out-injected.json")"
assert_eq "…and the plant moves exactly one pair out of the agreeing set" \
  "$((N_AGREE - 1))" "$INJ_AGREE"
assert_eq "…and into the differing one, so the control is a MEASUREMENT and not an exit code" \
  "$((N_DIFFER + 1))" "$INJ_DIFFER"
INJ_ROW="$(python3 -c '
import json,sys
d=json.load(open(sys.argv[1]))
r=[x for x in d["rows"] if x["id"]=="PublicDataLeafValue"][0]
print(r["verdict"], "|", " ".join(r["only_in_schema"]))' "$WORK/out-injected.json")"
assert_eq "…and the pair that AGREED now DIFFERS, naming the planted field" \
  "DIFFER | zzzFabricatedFieldThatIsInNoSchema" "$INJ_ROW"
assert_true "…and PublicDataLeafValue is in the agree set WITHOUT the plant" \
  grep -q '"PublicDataLeafValue"' <(python3 -c 'import json,sys;print(json.dumps(json.load(open(sys.argv[1]))["agree"]))' "$WORK/out.json")

# ---------------------------------------------------------------------------
# §6  What the comparison does NOT establish, asserted so it cannot be forgotten
# ---------------------------------------------------------------------------
# Set equality is not order equality, and msgpack maps are order-insensitive on
# decode but not on ENCODE — `avm_msgpack_coverage` compares re-packed BYTES, so a
# reordering would show there and not here. The two instruments answer different
# questions and this assertion is what says so.
N_ORDER="$(python3 -c '
import json,sys
d=json.load(open(sys.argv[1]))
print(sum(1 for r in d["rows"] if r.get("verdict")=="AGREE" and r.get("order_equal")))' "$WORK/out.json")"
assert_eq "of the agreeing pairs, the field ORDER is identical in every one" \
  "$N_AGREE" "$N_ORDER"

m37_finish
