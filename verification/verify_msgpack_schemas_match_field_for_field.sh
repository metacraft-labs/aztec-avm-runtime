#!/usr/bin/env bash
# verify_msgpack_schemas_match_field_for_field
#
# M37 verification: upstream's GENERATED IPC schemas compared against what this
# repository's wasm reactor exports actually take, FIELD FOR FIELD, as sets.
#
# THE CLAIM THIS CHECK EXISTS TO SETTLE, AND WHY IT IS NOT ALREADY SETTLED.
#
# `REACTOR-ABI.md` §"The host ABI is upstream's msgpack schemas" establishes, BY
# EXECUTION, that 42 crossed types round-trip and that 33 of them are declared in
# upstream files no overlay of ours touches. `DRIFT.md` D20 records, separately,
# that upstream moved the AVM and the world state OUT of the `@aztec/native` NAPI
# addon and behind a msgpack IPC boundary whose client, server and types are
# GENERATED by `ipc-codegen` from two schema files.
#
# From those two true statements the campaign has been saying that upstream's IPC
# client and our wasm reactor are "two transports over one schema". **That both
# sides use msgpack, and that our reactor's types are upstream's DECLARED types,
# is measured. That the GENERATED schemas are FIELD FOR FIELD what our exports
# take is NOT** — and M37's own section says in as many words not to promote it by
# repetition. This check makes the comparison and reports whatever it finds. A
# disagreement is a RESULT, recorded, not a failure to hide.
#
# WHAT IT COMPARES
#
#   schema side : barretenberg/cpp/src/barretenberg/wsdb/wsdb_schema.jsonc
#                 barretenberg/cpp/src/barretenberg/avm/avm_schema.json
#                 — both read out of the fork's OBJECT STORE at `anchors.cpp`,
#                   never out of a worktree, so this cannot measure a dirty tree.
#   our side    : the C++ types the reactor's exports pack and unpack, read out of
#                 the SAME object store at the SAME anchor, plus `AvmReactorError`,
#                 which is ours and is extracted from M12's own patch.
#
# The wire keys are decided by two macros that are NOT interchangeable:
# `SERIALIZATION_FIELDS` emits the C++ member names verbatim, and
# `MSGPACK_CAMEL_CASE_FIELDS` runs them through `msgpack_detail::camel_case` first.
# `_msgpack_schema_compare.py` transcribes that transform and its `--self-test`
# exercises it on the case a naive implementation gets wrong
# (`l1_to_l2_message_tree` -> `l1ToL2MessageTree`; `2` is not a lowercase letter).
# Normalising BOTH sides to some third spelling would make the comparison agree
# with itself by construction, which is why it is not done.
#
# THE CONTROLS. Three, because three different things could make this vacuous:
#
#   1. A FABRICATED FIELD planted on the schema side of a pair that AGREES must be
#      reported missing, by name. A comparer that cannot see a planted field cannot
#      see a real one.
#   2. The camelCase transform must be exercised, or every `MSGPACK_CAMEL_CASE_FIELDS`
#      type is compared through an identity function and the two spellings can never
#      be told apart.
#   3. Every pair must be READABLE. An unreadable pair prints `UNREADABLE` and is
#      counted; a comparison over a type the parser could not find would otherwise
#      look like a disagreement, and a comparison over an empty field list would
#      look like an agreement.
#
# Run: just verify-m37-msgpack

TEST_NAME="verify_msgpack_schemas_match_field_for_field"
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
. "$(dirname "${BASH_SOURCE[0]}")/lib_m37.sh"
m37_summary_on_abnormal_exit

command -v python3 >/dev/null 2>&1 || die "python3 is required"
command -v git >/dev/null 2>&1 || die "git is required"
[ -d "$FORK_ROOT/.git" ] || die "the aztec-packages fork is not at $FORK_ROOT"
[ -f "$REPO_ROOT/pins.json" ] || die "pins.json does not exist"

CMP="$VERIFY_DIR/_msgpack_schema_compare.py"
[ -f "$CMP" ] || die "the comparer is missing at $CMP"

M12_PATCH="$VERIFY_DIR/m12/0001-test-vm2-AVM_REACTOR-a-standalone-avm.wasm-reactor-a.patch"
[ -f "$M12_PATCH" ] || die "M12's reactor patch is missing at $M12_PATCH"

ANCHOR="$(python3 -c 'import json;print(json.load(open("'"$REPO_ROOT"'/pins.json"))["anchors"]["cpp"]["commit"])')"
[ -n "$ANCHOR" ] || die "could not read anchors.cpp out of pins.json"

WORK="${M37_MSGPACK_WORK:-$HOME/.cache/aztec-m37-msgpack}"
rm -rf "$WORK"
mkdir -p "$WORK/up" || die "could not create $WORK"

# ---------------------------------------------------------------------------
# §1  The inputs come out of the object store, and the anchor is the pinned one
# ---------------------------------------------------------------------------
printf '\n=== %s\n' "$TEST_NAME"

assert_eq "the anchor this comparison is taken at is pins.json's cpp anchor" \
  "commit" "$(git -C "$FORK_ROOT" cat-file -t "$ANCHOR" 2>/dev/null || echo missing)"
note "anchor: $ANCHOR"

WSDB_REL="barretenberg/cpp/src/barretenberg/wsdb/wsdb_schema.jsonc"
AVM_REL="barretenberg/cpp/src/barretenberg/avm/avm_schema.json"
UP_FILES="$WSDB_REL
$AVM_REL
barretenberg/cpp/src/barretenberg/crypto/merkle_tree/indexed_tree/indexed_leaf.hpp
barretenberg/cpp/src/barretenberg/crypto/merkle_tree/response.hpp
barretenberg/cpp/src/barretenberg/world_state_reference/merkle_tree_id.hpp
barretenberg/cpp/src/barretenberg/vm2/common/aztec_types.hpp
barretenberg/cpp/src/barretenberg/vm2/common/avm_io.hpp
barretenberg/cpp/src/barretenberg/bbapi/bbapi_shared.hpp"

n_up=0
while IFS= read -r rel; do
  [ -n "$rel" ] || continue
  mkdir -p "$WORK/up/$(dirname "$rel")"
  if git -C "$FORK_ROOT" show "$ANCHOR:$rel" > "$WORK/up/$rel" 2>/dev/null; then
    n_up=$((n_up + 1))
  else
    fail "the anchor does not carry $rel"
  fi
done <<EOF
$UP_FILES
EOF
assert_eq "every upstream input was materialised out of the object store" 8 "$n_up"

# `AvmReactorError` is OURS and lives in a file M12's patch ADDS, so it is
# extracted from the patch rather than from the fork. The extraction is asserted
# to have found the declaration, because an empty file would compare as
# UNREADABLE and read like a parser problem rather than like a broken extraction.
OURS="$WORK/avm_msgpack_coverage.cpp"
python3 - "$M12_PATCH" "$OURS" <<'PY'
import sys
patch, out = sys.argv[1], sys.argv[2]
lines = open(patch).read().split("\n")
keep, on = [], False
for ln in lines:
    if ln.startswith("+++ b/"):
        on = ln.endswith("vm2/reactor/avm_msgpack_coverage.cpp")
        continue
    if ln.startswith("--- ") or ln.startswith("diff --git"):
        continue
    if on and ln.startswith("+"):
        keep.append(ln[1:])
open(out, "w").write("\n".join(keep))
PY
assert_file "M12's added coverage translation unit was extracted from the patch" "$OURS"
assert_ge "…and it is not an empty extraction" 200 "$(wc -l < "$OURS" 2>/dev/null || echo 0)"
assert_true "…and it carries the AvmReactorError declaration this repository owns" \
  grep -q 'struct AvmReactorError' "$OURS"

# ---------------------------------------------------------------------------
# §2  The camelCase transform is a thing under test
# ---------------------------------------------------------------------------
SELFTEST="$(python3 "$CMP" --input /dev/null --self-test 2>&1)"
st_rc=$?
assert_eq "the comparer's camelCase self-test exits 0" "0" "$st_rc"
assert_contains "…over a non-empty case list" '"camel_case_cases": 6' "$SELFTEST"
assert_contains "…with nothing wrong" '"wrong": {}' "$SELFTEST"
# The transform must not be an identity, or every camel-cased type is compared
# through a function that changes nothing and the two spellings cannot differ.
assert_eq "…and the transform actually transforms, so it is not an identity" \
  "l1ToL2MessageTree" \
  "$(python3 -c 'import importlib.util,sys
spec=importlib.util.spec_from_file_location("c",sys.argv[1]);m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m)
print(m.camel_case("l1_to_l2_message_tree"))' "$CMP")"

# ---------------------------------------------------------------------------
# §3  The pairs. Each is (schema declaration, C++ type) with a reason.
# ---------------------------------------------------------------------------
U="$WORK/up/barretenberg/cpp/src/barretenberg"
python3 - "$WORK" "$U" "$OURS" <<'PY'
