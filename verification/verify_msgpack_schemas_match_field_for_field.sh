json.dump({"pairs": pairs, "inject": {}}, open(f"{W}/input.json", "w"), indent=1)
# The injected control goes on a pair that AGREES, so the only thing that can
# make it differ is the plant.
inj = dict(json.load(open(f"{W}/input.json")))
