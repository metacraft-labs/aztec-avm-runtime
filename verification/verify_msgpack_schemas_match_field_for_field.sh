   why="wsdb SequentialInsertPublicData carries it; avm_merkle_db_insert_indexed_leaves_public_data_tree unpacks exactly this type"),
 P(id="IndexedNullifierLeafValue", schema_kind="type", schema_file=WSDB, schema_name="IndexedNullifierLeafValue",
   cpp_file=IL, cpp_type="IndexedLeaf",
   why="wsdb GetNullifierLeafPreimage returns it; avm_merkle_db_get_leaf_preimage_nullifier_tree returns IndexedLeaf<NullifierLeafValue>"),
 P(id="IndexedPublicDataLeafValue", schema_kind="type", schema_file=WSDB, schema_name="IndexedPublicDataLeafValue",
   cpp_file=IL, cpp_type="IndexedLeaf",
   why="wsdb GetPublicDataLeafPreimage returns it; avm_merkle_db_get_leaf_preimage_public_data_tree returns IndexedLeaf<PublicDataLeafValue>"),
 P(id="WorldStateRevision", schema_kind="type", schema_file=WSDB, schema_name="WorldStateRevision",
   cpp_file=MT, cpp_type="WorldStateRevision",
   why="every wsdb read command takes one; REACTOR-ABI.md lists WorldStateRevision among the 33 upstream schemas the reactor crosses"),
 P(id="SiblingPathAndIndex", schema_kind="type", schema_file=WSDB, schema_name="SiblingPathAndIndex",
