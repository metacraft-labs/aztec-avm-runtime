W, U, OURS = sys.argv[1], sys.argv[2], sys.argv[3]
WSDB = f"{U}/wsdb/wsdb_schema.jsonc"
AVM  = f"{U}/avm/avm_schema.json"
IL   = f"{U}/crypto/merkle_tree/indexed_tree/indexed_leaf.hpp"
RS   = f"{U}/crypto/merkle_tree/response.hpp"
MT   = f"{U}/world_state_reference/merkle_tree_id.hpp"
AT   = f"{U}/vm2/common/aztec_types.hpp"
IO   = f"{U}/vm2/common/avm_io.hpp"
BB   = f"{U}/bbapi/bbapi_shared.hpp"

P = lambda **k: k
pairs = [
 P(id="NullifierLeafValue", schema_kind="type", schema_file=WSDB, schema_name="NullifierLeafValue",
   cpp_file=IL, cpp_type="NullifierLeafValue",
   why="wsdb AppendNullifierLeaves and FindNullifierLeafIndices carry it; avm_merkle_db_insert_indexed_leaves_nullifier_tree unpacks exactly this type"),
